    /// Fixture-only fixed-column framing. Numeric parameter records above are never generated by a production writer.
    private func literal(_ records: [Record]) -> Data {
        func integer(_ value: Int, width: Int) -> String {
            let digits = String(value); return String(repeating: " ", count: max(0, width-digits.count)) + digits
        }
        func padded(_ value: String, _ width: Int) -> String {
            value + String(repeating: " ", count: max(0, width-value.count))
        }
        func pieces(_ value: String, width: Int) -> [String] {
            var result: [String] = [], cursor = value.startIndex
            while cursor < value.endIndex {
                let end = value.index(cursor, offsetBy: width, limitedBy: value.endIndex) ?? value.endIndex
                result.append(String(value[cursor..<end])); cursor = end
            }
            return result
        }
        let global = "1H,,1H;,7Hfixture,15Hindependent.igs,7Hfixture,7Hfixture,32,38,6,308,15,1.0,2,2,2HMM,1,0.001,15H20261005.000000,1.E-6,0.,6Hauthor,7Hfixture,11,0,15H20261005.000000;"
        let globalPieces = pieces(global, width: 72)
        var lines = [padded("Independently authored rational geometry and nested groups",72)+"S"+integer(1,width:7)]
        for (index, piece) in globalPieces.enumerated() { lines.append(padded(piece,72)+"G"+integer(index+1,width:7)) }
        var parameterLines: [String] = [], sequence = 1
        for (index, record) in records.enumerated() {
            let pointer = index*2+1, chunks = pieces(record.data, width:64)
            let first = [record.type,sequence,0,0,0,0,record.transformation,0]
                .map { integer($0,width:8) }.joined()+"00000000"
            let second = [record.type,0,0,chunks.count,record.form,0,0]
                .map { integer($0,width:8) }.joined()+padded(record.label,8)+integer(0,width:8)
            lines.append(first+"D"+integer(pointer,width:7)); lines.append(second+"D"+integer(pointer+1,width:7))
            for chunk in chunks {
                parameterLines.append(padded(chunk,64)+integer(pointer,width:8)+"P"+integer(sequence,width:7)); sequence += 1
            }
        }
        lines += parameterLines
        let terminate = "S"+integer(1,width:7)+"G"+integer(globalPieces.count,width:7)+"D"+integer(records.count*2,width:7)+"P"+integer(parameterLines.count,width:7)
        lines.append(padded(terminate,72)+"T"+integer(1,width:7))
        return Data((lines.joined(separator:"\n")+"\n").utf8)
    }

    private func imported(_ bytes: Data) throws -> CADDocument {
        let result = try IGESExchange(tolerance: .standard).import(bytes)
        #expect(result.brep == nil && result.meshes.isEmpty)
        return try #require(result.document)
    }
    private func inspect(_ source: IndependentShapeSource) throws {
        #expect(source.geometry.curves.count == 1 && source.geometry.surfaces.count == 1 && source.items.count == 2)
        #expect(source.groups.count == 2 && source.definitions.count == 2 && source.instances.count == 2)
        #expect(source.representations.count == 2 && source.frames.isEmpty)
        #expect(source.definitions.allSatisfy { $0.originFrameID == nil })
        let local = try #require(source.groups.first { $0.name == "LOCAL" })
        let global = try #require(source.groups.first { $0.name == "GLOBAL" })
        #expect(global.members.contains(.group(local.id)))
        let leaf = try #require(source.representations.first { $0.name == "leaf" })
        #expect(leaf.members == [.group(local.id)])
        let curveItem = try #require(source.items.first { $0.name == "C1" })
        guard case .curve(let curveID, let trim) = curveItem.geometry,
              case .bSpline(let curve) = source.geometry.curves[curveID] else {
            Issue.record("The literal requires its original rational curve."); return
        }
        #expect(trim?.startParameter == 0 && trim?.endParameter == 1)
        #expect(curve.degree == 1 && curve.knots == [0,0,1,1] && curve.weights == [1,2])
        for t in [0.0,0.25,0.5,1] {
            #expect((try curve.point(at:t,tolerance:.standard)-Point3D(x:0.02*t/(1+t),y:0,z:0)).length <= ModelingTolerance.standard.distance)
        }
        let surfaceItem = try #require(source.items.first { $0.name == "S1" })
        guard case .surface(let surfaceID) = surfaceItem.geometry,
              case .bSpline(let surface) = source.geometry.surfaces[surfaceID] else {
            Issue.record("The literal requires its original tensor surface."); return
        }
        #expect(surface.uDegree == 1 && surface.vDegree == 1)
        #expect(surface.uKnots == [0,0,1,1] && surface.vKnots == [0,0,1,1])
        for u in [0.0,0.25,1] { for v in [0.0,0.7,1] {
            #expect((try surface.point(u:u,v:v,tolerance:.standard)-Point3D(x:0.01*u,y:0.02*v,z:0.005*u)).length <= ModelingTolerance.standard.distance)
        } }
        let inner = try #require(source.instances.first { $0.name == "INNER" })
        let top = try #require(source.instances.first { $0.name == "TOP" })
        #expect(inner.placementName == "TURN" && top.placementName == "")
        let point = Point3D(x:0.0025,y:0.014,z:0.00125)
        #expect((inner.placement.applying(to:point)-Point3D(x:-0.018,y:0.025,z:0.0325)).length <= ModelingTolerance.standard.distance)
        #expect((top.placement.applying(to:inner.placement.applying(to:point))-Point3D(x:0.082,y:0.025,z:0.0325)).length <= ModelingTolerance.standard.distance)
        #expect(source.roots == [.group(global.id)])
    }

    @Test(.timeLimit(.minutes(1)))
    func independentLiteralAndTwoIGESGenerationsRetainNestedSharedOriginalGeometry() throws {
        var document = try imported(literal(records))
        try inspect(try #require(document.independentShapes))
        let native = NativePackageStore(tolerance:.standard), sink = DataByteSink()
        try native.writePackage(for:document,to:sink)
        #expect(try native.loadDocument(from:sink.bytes) == document)
        for _ in 0..<2 {
            let output = DataByteSink()
            try IGESExchange(tolerance:.standard).write(document,to:output)
            document = try imported(output.bytes)
            try inspect(try #require(document.independentShapes))
        }
    }

    @Test(.timeLimit(.minutes(1)))
    func standaloneOriginalIGESGeometryRetainsUnequalAxesWithoutInventedGroups() throws {
        var document = try imported(literal(Array(records.prefix(2))))
        for generation in 0..<3 {
            let source = try #require(document.independentShapes)
            #expect(source.groups.isEmpty && source.representations.isEmpty && source.definitions.isEmpty && source.instances.isEmpty)
            #expect(source.geometry.curves.count == 1 && source.geometry.surfaces.count == 1 && source.items.count == 2)
            #expect(source.roots == source.items.map { IndependentShapeReference.item($0.id) }.sorted())
            let curve = try #require(source.geometry.curves.values.first)
            #expect((try curve.point(at:0.25,tolerance:.standard)-Point3D(x:0.004,y:0,z:0)).length <= ModelingTolerance.standard.distance)
            let surface = try #require(source.geometry.surfaces.values.first)
            #expect((try surface.point(u:0.25,v:0.7,tolerance:.standard)-Point3D(x:0.0025,y:0.014,z:0.00125)).length <= ModelingTolerance.standard.distance)
            if generation < 2 {
                let output = DataByteSink()
                try IGESExchange(tolerance:.standard).write(document,to:output)
                document = try imported(output.bytes)
            }
        }
    }

    @Test(.timeLimit(.minutes(1)))
    func originalPlaneReferenceDirectionIsNotReplacedByADirectoryLabel() throws {
        let plane = [Record(type:116,form:0,label:"",transformation:0,data:"116,100,200,300,0;"),
            Record(type:123,form:0,label:"",transformation:0,data:"123,0,0,1;"),
            Record(type:123,form:0,label:"",transformation:0,data:"123,3,4,0;"),
            Record(type:190,form:1,label:"P1",transformation:0,data:"190,1,3,5;")]
        var document = try imported(literal(plane))
        let native = DataByteSink(); try OfficialFormatExchange(tolerance:.standard).write(document,as:.swiftCAD,to:native)
        #expect(try OfficialFormatExchange(tolerance:.standard).import(native.bytes,as:.swiftCAD).document == document)
        for generation in 0..<3 {
            let source = try #require(document.independentShapes)
            #expect(source.items.count == 1 && source.geometry.surfaces.count == 1 && source.geometry.curves.isEmpty)
            guard case .surface(let id) = source.items[0].geometry, case .plane(let value) = source.geometry.surfaces[id] else {
                Issue.record("Original IGES plane chart was substituted."); return
            }
            #expect(source.items[0].name == "P1" && source.surfaceNames[id] == "P1")
            #expect(value.uDirection == Vector3D(x:0.6,y:0.8,z:0))
            let position = try Surface3D.plane(value).point(u:document.units.length.toInternal(5),v:document.units.length.toInternal(-2),tolerance:.standard)
            #expect((position-Point3D(x:0.1046,y:0.2028,z:0.3)).length < 1e-12)
            if generation < 2 {
                let sink = DataByteSink(); try IGESExchange(tolerance:.standard).write(document,to:sink)
                document = try #require(IGESExchange(tolerance:.standard).import(sink.bytes).document)
            }
        }
    }

    @Test(.timeLimit(.minutes(1)))
    func publicIGESMemoryURLResourceCancellationAndMetadataLossAreAtomic() async throws {
        let document = try imported(literal(records)), original = try #require(document.independentShapes)
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        try FileManager.default.createDirectory(at:directory,withIntermediateDirectories:true)
        defer { do { try FileManager.default.removeItem(at:directory) } catch { Issue.record("Unable to remove independent IGES fixture: \(error)") } }
        let url = directory.appendingPathComponent("independent.igs"), exchange = OfficialFormatExchange(tolerance:.standard)
        try exchange.export(document,as:.iges,to:url)
        let read = try exchange.import(from:url)
        try inspect(try #require(read.document?.independentShapes))
        let prior = try Data(contentsOf:url)
        let bounded = OfficialFormatExchange(tolerance:.standard,
            igesExchange:IGESExchange(tolerance:.standard,resourceLimits:.init(maximumIterations:1)))
        func resource(_ body:() throws -> Void) throws {
            do { try body(); Issue.record("Caller IGES resource ceiling was reset.") }
            catch IndependentShapeSourceError.resourceLimitExceeded { }
            catch IndependentShapeExchangeError.resourceLimitExceeded { }
            catch let error as KernelError { #expect(error.code == .resourceLimitExceeded) }
        }
        let sink = DataByteSink()
        try resource { try bounded.write(document,as:.iges,to:sink) }
        #expect(sink.bytes.isEmpty)
        try resource { try bounded.export(document,as:.iges,to:url) }
        #expect(try Data(contentsOf:url) == prior)
        let groups = original.groups.enumerated().map { index, group in
            IndependentShapeGroup(id:group.id,name:group.name,description:index == 0 ? "" : group.description,members:group.members)
        }
        var descriptive = document
        descriptive.independentShapes = IndependentShapeSource(geometry:original.geometry,items:original.items,
            geometricSets:original.geometricSets,contexts:original.contexts,representations:original.representations,
            frames:original.frames,definitions:original.definitions,curveNames:original.curveNames,surfaceNames:original.surfaceNames,
            groups:groups,instances:original.instances,roots:original.roots)
        let failure = IndependentShapeExchangeError.metadataLoss("IGES unordered group has no description transport.")
        #expect(throws:failure) { try exchange.write(descriptive,as:.iges,to:sink) }
        #expect(sink.bytes.isEmpty)
        #expect(throws:failure) { try exchange.export(descriptive,as:.iges,to:url) }
        #expect(try Data(contentsOf:url) == prior)
        let task = Task {
            while !Task.isCancelled { await Task.yield() }
            let output = DataByteSink()
            do { try exchange.write(document,as:.iges,to:output); Issue.record("Cancelled original IGES write succeeded.") }
            catch is CancellationError { }
            #expect(output.bytes.isEmpty)
        }
        task.cancel(); try await task.value
    }

    @Test(.timeLimit(.minutes(1)))
    func originalDepthDuplicateMembershipAndUnretainedDefinitionTransformRefuse() throws {
        var wrong = records
        wrong[6] = .init(type:308,form:0,label:"",transformation:0,data:"308,0,6Hparent,1,11;")
        #expect(throws:IndependentShapeExchangeError.invalidAssociation("IGES308 declared depth disagrees with actual nested definitions.")) { try imported(literal(wrong)) }
        wrong = records
        wrong[2] = .init(type:402,form:7,label:"LOCAL",transformation:0,data:"402,2,1,1;")
        #expect(throws:IndependentShapeExchangeError.invalidAssociation("Duplicate IGES group/subfigure member.")) { try imported(literal(wrong)) }
        wrong = records
        wrong[3] = .init(type:308,form:0,label:"",transformation:9,data:"308,0,4Hleaf,1,5;")
        #expect(throws:IndependentShapeExchangeError.unsupportedSemantics("IGES308 defining transformation has no retained source owner.")) { try imported(literal(wrong)) }
    }
